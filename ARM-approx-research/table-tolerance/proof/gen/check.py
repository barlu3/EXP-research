#!/usr/bin/env python3
"""Ties the proof to the measurements, and writes its results table.

Reads eps_star.csv (from Search.lean) and measured_logf.csv (extracted once from
table_tolerance_logf.txt, by `check.py --extract <report>`, since the report needs
Apple Silicon and these checks run anywhere). Fails if:

  - Arm's RecipEstimate pseudocode, which the proof uses, differs from what the
    hardware's FRECPE returned;
  - any proven drift is past B4's measured bound. B4's search stops within a factor
    of 1 + 3/256 of the first failing drift, so past that is past a known
    counterexample, and the model behind the proof would be wrong.

Standard library only.
"""

import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEX = HERE.parent / "tex" / "cells-table.tex"
B4_STEP = 1 + 3 / 256        # table-tolerance.cpp's tolerance_search stops at 0x1.03p0

# The scan of every c on the 29-bit grid around cell 68's upward bound.
SCAN_CELL, SCAN_EDGE = 68, 3.874576446e-02


def recip_estimate(i):
    """Arm's RecipEstimate for cell i, as a float in [1/2, 1)."""
    a = 2 * (256 + i) + 1
    return ((2 ** 19 // a + 1) // 2) / 512


def eps(row, key):
    """A proven drift from eps_star.csv, whose units are exact multiples of 2^-22."""
    return int(row[key + "_units"]) / 2 ** 22


def extract(report):
    chat, b4, section = {}, {}, None
    for line in Path(report).read_text().splitlines():
        if "B1. FRECPE" in line:
            section = "B1"
        elif "B2. FRECPE" in line:
            section = None
        elif "B4. FRECPE" in line:
            section = "B4"
        elif "tightest:" in line:
            section = None
        if section == "B1":
            m = re.match(r"\s*(\d+)\s+(0x\S+)\s+\d+\s", line)
            if m:
                chat[int(m[1])] = m[2]
        elif section == "B4":
            m = re.match(r"\s*(\d+)\s+0x\S+\s+>?\s*(-?[\d.e+-]+)\s+>?\s*([\d.e+-]+)\s", line)
            if m:
                b4[int(m[1])] = (m[2], m[3])
    if len(chat) != 256 or len(b4) != 256:
        sys.exit(f"expected 256 cells in {report}: B1 has {len(chat)}, B4 has {len(b4)}")
    with open(HERE / "measured_logf.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["cell", "chat_hex", "eps_down", "eps_up"])
        for i in range(256):
            w.writerow([i, chat[i], *b4[i]])


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--extract":
        extract(sys.argv[2])
        return

    measured = list(csv.DictReader(open(HERE / "measured_logf.csv")))
    proven = list(csv.DictReader(open(HERE / "eps_star.csv")))
    bad = [m["cell"] for m in measured
           if float.fromhex(m["chat_hex"]) != recip_estimate(int(m["cell"]))]
    if bad:
        sys.exit(f"RecipEstimate differs from the hardware in cells {bad}")

    rows = []
    for m, p in zip(measured, proven):
        i = int(m["cell"])
        for side, key in (("down", "eps_down"), ("up", "eps_up")):
            star, meas = eps(p, key), abs(float(m[key]))
            if star > meas * B4_STEP:
                sys.exit(f"cell {i} {side}: proven {star} is past the measured {meas}")
            rows.append((i, side, star, meas))

    star68 = eps(proven[SCAN_CELL], "eps_up")
    if star68 > SCAN_EDGE:
        sys.exit(f"cell {SCAN_CELL} up: proven {star68} is past the scanned edge {SCAN_EDGE}")

    ratios = sorted(s / m for _, _, s, m in rows)
    print(f"256 RecipEstimate values match the hardware")
    print(f"512 sides: proven/measured min {ratios[0]:.3f}, "
          f"median {ratios[len(ratios) // 2]:.3f}, max {ratios[-1]:.3f}; none past B4's final search step")
    print(f"cell {SCAN_CELL} up: proven {star68:.6%}, scanned edge {SCAN_EDGE:.6%}")

    with open(TEX, "w") as f:
        f.write("% Generated by gen/check.py.\n")
        for m, p in zip(measured, proven):
            f.write(f"{m['cell']} & \\texttt{{{m['chat_hex']}}} & {eps(p, 'eps_down') * 100:.4f} & "
                    f"{abs(float(m['eps_down'])) * 100:.4f} & {eps(p, 'eps_up') * 100:.4f} & "
                    f"{float(m['eps_up']) * 100:.4f} \\\\\n")


if __name__ == "__main__":
    main()
