__bf16 cr_sin_bf16 (__bf16 x){
  b16u16_u v = {.f = x};
  uint16_t u = v.u, au = u & 0x7fff;

  static const float sgn[] = {1.0, -1.0};

  // for |x| <= 0x1.dp-4, sin(x) rounds to x to nearest
  if (au <= 0x3de8) { // |x| <= 0x1.dp-4
    if (au == 0) return x; // x = +0 or -0
    float res;
    // avoid spurious underflow for |x|=0x1p-126
    // res = (au == 0x80) ? sgn[u>>15] * 0x1.fffffffffffffp-127
    res = (au == 0x80) ? sgn[u>>15] * 0x1.fffffcp-127f
      : x * 0x1.fffffep-1f;
#ifdef CORE_MATH_SUPPORT_ERRNO
    if (__builtin_fabsf (res) < 0x1p-126)
      errno = ERANGE; // underflow
#endif
    return res;
  }

  // now 0x3de8 < au, |x| > 0x1.dp-4
  
  if (au < 0x4580) { // |x| < 4096
    // the exponent part lies in [123,138]
    uint16_t i1 = (au - 0x3d80) >> 3; // 0x3d80 is 123<<7
    uint16_t i2 = (((au - 0x3d80) >> 7) << 3) | (au & 0x7);
    // we use a FMA to fix the evaluation order
    float res = __builtin_fmaf (S1[i1], C2[i2], C1[i1] * S2[i2]);
    return sgn[u>>15] * res;
  }

  if ((au >> 7) == 0xff) { // NaN or Inf
    b16u16_u qnan = {.u = 0x7fc0};
    return qnan.f + x;
  }

  /* now |x| >= 4096 thus ulp(x) >= 32.
     We write |x| = b0*2^i + ... + b7*2^(i+7).
     We tabulate the values of sin(2^i) and cos(2^i) for 5 <= i < 128 and use
     the relations:
     sin(a+b) = sin(a)*cos(b) + cos(a)*sin(b)
     cos(a+b) = cos(a)*cos(b) - sin(a)*sin(b) */

  int k = (au >> 7) - 0x8b; // k=0 for |x|=4096
  float s = S3[k+7], c = C3[k+7]; // sin/cos of b7*2^(i+7)
  for (int j = 0; j < 7; j++)
    if ((au >> j) & 1) {
      float t = __builtin_fmaf (s, C3[k+j], c * S3[k+j]);
      c = __builtin_fmaf (c, C3[k+j], -s * S3[k+j]);
      s = t;
    }
  return sgn[u>>15] * s;
}

